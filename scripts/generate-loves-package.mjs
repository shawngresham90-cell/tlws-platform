/**
 * Generates the guarded Love's import package from the reconciliation CSVs.
 *
 * Every value in the emitted SQL comes from the committed CSVs, which come from
 * the checksummed source workbook — nothing is hand-transcribed. Re-running
 * regenerates the package byte-for-byte.
 *
 * NOTHING HERE IS EXECUTED. It writes .sql files under data/imports/.
 *
 * Run: node scripts/generate-loves-package.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';

const SRC = 'data/sources/loves-master/2026-07-27';
const OUT = 'data/imports/loves-2026-07-27';
mkdirSync(OUT, { recursive: true });

const parseCsv = (text) => {
  const rows = [];
  let row = [],
    field = '',
    quoted = false;
  for (let i = 0; i < text.length; i++) {
    const c = text[i];
    if (quoted) {
      if (c === '"') {
        if (text[i + 1] === '"') {
          field += '"';
          i++;
        } else quoted = false;
      } else field += c;
    } else if (c === '"') quoted = true;
    else if (c === ',') {
      row.push(field);
      field = '';
    } else if (c === '\n') {
      row.push(field);
      rows.push(row);
      row = [];
      field = '';
    } else if (c !== '\r') field += c;
  }
  if (field.length || row.length) {
    row.push(field);
    rows.push(row);
  }
  const head = rows[0];
  return rows.slice(1).map((r) => Object.fromEntries(head.map((h, i) => [h, r[i] ?? ''])));
};
const read = (f) => parseCsv(readFileSync(`${SRC}/${f}`, 'utf8').trim());

const directory = read('DIRECTORY-615.csv');
const enrich = read('ENRICHMENT-PLAN.csv');
const services = read('COLOCATED-SERVICE-ROWS.csv');
const netNew = directory.filter((r) => r.disposition === 'net-new');

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const nq = (v) => (v === '' || v === null || v === undefined ? 'null' : String(v));
const bool = (v) => (v === 'true' ? 'true' : 'false');

/* detail_slug matches the directory's existing convention: name-city-state,
   lowercased, non-alphanumerics collapsed to hyphens. */
const slugify = (s) =>
  String(s)
    .toLowerCase()
    .normalize('NFKD')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '');
const detailSlug = (r) => slugify(`${r.name} ${r.city} ${r.state}`);

/* ============================================================ 1. NET-NEW */
// One transaction per state. Every row unpublished, unfeatured, is_indexable
// untouched (the column has a NOT NULL default and is never named here).
const byState = new Map();
for (const r of netNew) byState.set(r.state, [...(byState.get(r.state) ?? []), r]);

let ins = `-- Love's net-new locations — GUARDED, ONE TRANSACTION PER STATE.
--
-- NOT EXECUTED. Generated by scripts/generate-loves-package.mjs from
-- data/sources/loves-master/2026-07-27/DIRECTORY-615.csv, which derives from
-- LovesSearchResults.xlsx (sha256 ec5146ee…a89ab2, confirmed by Love's own
-- published count of 731 locations).
--
-- ${netNew.length} rows across ${byState.size} states.
--   ${netNew.filter((r) => r.overnight_eligible === 'true').length} overnight-eligible
--   ${netNew.filter((r) => r.overnight_eligible === 'false').length} NOT overnight-eligible — directory only, never parking
--
-- Every inserted row is is_published = false and is_featured = false.
-- is_indexable is never written; it keeps its column default.
-- overnight_parking carries the operator's own flag, so a non-overnight store
-- can never be surfaced as HOS-rest parking.
--
-- Run one state at a time. A bad state fails alone.

`;

for (const [state, rowsIn] of [...byState].sort()) {
  const overnightN = rowsIn.filter((r) => r.overnight_eligible === 'true').length;
  ins += `-- ============================================================ ${state} (${rowsIn.length} rows, ${overnightN} overnight)
begin;

create temporary table _new (
  source_ref text primary key, name text, address text, city text, state char(2),
  zip text, lat double precision, lng double precision, interstate text,
  exit_number text, parking_spaces int, overnight boolean, detail_slug text
) on commit drop;

insert into _new values
${rowsIn
  .map(
    (r) =>
      `  (${q(r.source_ref)}, ${q(r.name)}, ${q(r.address)}, ${q(r.city)}, ${q(r.state)}, ${q(r.zip)}, ` +
      `${nq(r.lat)}, ${nq(r.lng)}, ${r.interstate ? q(r.interstate) : 'null'}, ` +
      `${r.exit_number ? q(r.exit_number) : 'null'}, ${nq(r.parking_spaces)}, ${bool(r.overnight_eligible)}, ${q(detailSlug(r))})`,
  )
  .join(',\n')};

do $$
declare n integer; batch integer;
begin
  select count(*) into batch from _new;
  if batch <> ${rowsIn.length} then
    raise exception 'Expected ${rowsIn.length} ${state} rows staged, found %.', batch;
  end if;

  -- 1. Coordinates required for every inserted row, in-state envelope.
  select count(*) into n from _new
   where lat is null or lng is null or lat = 0 or lng = 0
      or lat not between 24.0 and 49.5 or lng not between -125.0 and -66.5;
  if n <> 0 then raise exception '% row(s) have an unusable coordinate.', n; end if;

  -- 2. No duplicate coordinate inside the batch (map-pin collision guard).
  select count(*) into n from (select lat, lng from _new group by lat, lng having count(*) > 1) d;
  if n <> 0 then raise exception '% coordinate(s) shared by more than one site.', n; end if;

  -- 3. detail_slug must be unique in the batch and free in the table.
  select count(*) into n from (select detail_slug from _new group by detail_slug having count(*) > 1) d;
  if n <> 0 then raise exception '% duplicate detail_slug(s) inside the batch.', n; end if;
  select count(*) into n from _new x join public.locations l on l.detail_slug = x.detail_slug;
  if n <> 0 then raise exception '% detail_slug(s) already exist in locations.', n; end if;

  -- 4. Store number must not already be present for this state.
  select count(*) into n
    from _new x join public.locations l
      on l.state = x.state and substring(l.name from '#\\s*(\\d+)') = x.source_ref
   where l.deleted_at is null and l.name !~* '^(boss truck shop|speedco)';
  if n <> 0 then raise exception '% store number(s) already exist in ${state}.', n; end if;

  -- 5. Proximity: refuse to drop a pin within ~150 m of a published location.
  select count(*) into n
    from _new x join public.locations l
      on l.deleted_at is null and l.is_published and l.lat is not null
     and abs(l.lat - x.lat) < 0.0015 and abs(l.lng - x.lng) < 0.0015;
  if n <> 0 then raise exception '% row(s) sit within ~150 m of a published location.', n; end if;

  -- 6. Insert. UNPUBLISHED, UNFEATURED, is_indexable untouched.
  insert into public.locations
    (type, category_slug, name, address, city, state, zip, lat, lng,
     interstate, exit_number, parking_spaces, overnight_parking,
     slug, detail_slug, source, is_published, is_featured)
  select 'truck_stop', 'truck-stops', x.name, x.address, x.city, x.state, x.zip, x.lat, x.lng,
         x.interstate, x.exit_number, x.parking_spaces, x.overnight,
         x.detail_slug, x.detail_slug, 'loves-master-2026-07-27', false, false
    from _new x;
  get diagnostics n = row_count;
  if n <> ${rowsIn.length} then
    raise exception 'Expected to insert exactly ${rowsIn.length} row(s), inserted %.', n;
  end if;

  -- 7. Nothing may be published or featured by this statement.
  select count(*) into n from public.locations
   where source = 'loves-master-2026-07-27' and state = ${q(state)} and (is_published or is_featured);
  if n <> 0 then raise exception 'Post-check failed: % row(s) are published/featured.', n; end if;
end $$;

commit;

`;
}
writeFileSync(`${OUT}/INSERT-NET-NEW.sql`, ins);

/* ========================================================== 2. ENRICHMENT */
let enr = `-- Love's enrichment of EXISTING rows — GUARDED, blank-only, exact id.
--
-- NOT EXECUTED. ${enrich.length} rows, all of them the \`truck-stops\` record for
-- a Love's site. THE MAP-PIN RULE: only this row receives a coordinate. The
-- ${services.length} colocated CAT scale / truck care / truck wash rows at the same
-- addresses are reconciled in COLOCATED-SERVICE-ROWS.csv and deliberately get
-- NO coordinate, so the collision guard is never weakened and the map never
-- shows two pins for one site.
--
-- Blank-only: refuses to overwrite a coordinate that already exists.

begin;

create temporary table _enr (
  db_id uuid primary key, source_ref text, lat double precision, lng double precision,
  interstate text, exit_number text, parking_spaces int, overnight boolean
) on commit drop;

insert into _enr values
${enrich
  .map(
    (r) =>
      `  (${q(r.db_id)}, ${q(r.source_ref)}, ${nq(r.lat)}, ${nq(r.lng)}, ` +
      `${r.interstate ? q(r.interstate) : 'null'}, ${r.exit_number ? q(r.exit_number) : 'null'}, ` +
      `${nq(r.parking_spaces)}, ${bool(r.overnight_eligible)})`,
  )
  .join(',\n')};

do $$
declare n integer; batch integer;
begin
  select count(*) into batch from _enr;
  if batch <> ${enrich.length} then
    raise exception 'Expected ${enrich.length} staged rows, found %.', batch;
  end if;

  -- 1. Every id resolves to a live row.
  select count(*) into n from _enr e join public.locations l on l.id = e.db_id where l.deleted_at is null;
  if n <> batch then raise exception '% id(s) do not resolve to a live row.', batch - n; end if;

  -- 2. Every target is the truck-stops record — the only row that gets a pin.
  select count(*) into n from _enr e join public.locations l on l.id = e.db_id
   where l.category_slug <> 'truck-stops';
  if n <> 0 then raise exception '% target(s) are not truck-stops rows; only the map-pin row may be enriched.', n; end if;

  -- 3. BLANK-ONLY. Never overwrite an existing coordinate.
  select count(*) into n from _enr e join public.locations l on l.id = e.db_id
   where l.lat is not null or l.lng is not null;
  if n <> 0 then raise exception '% target(s) already carry coordinates; this statement never overwrites.', n; end if;

  -- 4. Coordinates plausible and in the row's own state envelope.
  select count(*) into n from _enr
   where lat is null or lng is null or lat = 0 or lng = 0
      or lat not between 24.0 and 49.5 or lng not between -125.0 and -66.5;
  if n <> 0 then raise exception '% coordinate(s) unusable.', n; end if;

  -- 5. No two sites share a coordinate.
  select count(*) into n from (select lat, lng from _enr group by lat, lng having count(*) > 1) d;
  if n <> 0 then raise exception '% coordinate(s) shared by more than one site.', n; end if;

  -- 6. Store number on the row must match the source ref it is being given.
  select count(*) into n from _enr e join public.locations l on l.id = e.db_id
   where coalesce(substring(l.name from '#\\s*(\\d+)'), '') <> e.source_ref;
  if n <> 0 then raise exception '% row(s) have a store number that disagrees with the source.', n; end if;

  -- 7. Write. Authorized fields only; publication state untouched.
  update public.locations l
     set lat = e.lat, lng = e.lng,
         interstate = coalesce(l.interstate, e.interstate),
         exit_number = coalesce(l.exit_number, e.exit_number),
         parking_spaces = coalesce(l.parking_spaces, e.parking_spaces),
         overnight_parking = e.overnight,
         geocode_source = 'batch-csv',
         geocode_confidence = 'high',
         coord_verification_status = 'machine-checked',
         last_geocoded_at = now(), updated_at = now()
    from _enr e
   where l.id = e.db_id and l.lat is null and l.lng is null;
  get diagnostics n = row_count;
  if n <> batch then raise exception 'Expected to enrich exactly % row(s), updated %.', batch, n; end if;

  -- 8. Enrichment must never publish.
  select count(*) into n from _enr e join public.locations l on l.id = e.db_id
   where l.is_featured;
  if n <> 0 then raise exception 'Post-check failed: % row(s) became featured.', n; end if;
end $$;

commit;
`;
writeFileSync(`${OUT}/ENRICH-EXISTING.sql`, enr);

/* ============================================================== 3. CANARY */
// Ten overnight-eligible sites, maximally diverse: distinct states, distinct
// corridors, weighted to corridors the directory currently has nothing on.
const PRIORITY = ['I-80', 'I-94', 'I-90', 'I-10', 'I-15', 'I-70', 'I-35', 'I-5', 'I-95', 'I-40'];
const overnightNetNew = netNew.filter((r) => r.overnight_eligible === 'true' && r.interstate);
const canary = [];
const usedState = new Set(),
  usedCorr = new Set();
for (const corr of PRIORITY) {
  const c = overnightNetNew
    .filter((r) => r.interstate === corr && !usedState.has(r.state) && !usedCorr.has(r.interstate))
    .sort((a, b) => Number(b.parking_spaces) - Number(a.parking_spaces))[0];
  if (c) {
    canary.push(c);
    usedState.add(c.state);
    usedCorr.add(c.interstate);
  }
  if (canary.length === 10) break;
}
for (const r of overnightNetNew.sort(
  (a, b) => Number(b.parking_spaces) - Number(a.parking_spaces),
)) {
  if (canary.length === 10) break;
  if (!usedState.has(r.state) && !usedCorr.has(r.interstate)) {
    canary.push(r);
    usedState.add(r.state);
    usedCorr.add(r.interstate);
  }
}

let can = `-- Love's publication CANARY — 10 locations, GUARDED.
--
-- NOT EXECUTED. Publication requires separate authorization, distinct from
-- insertion and from enrichment.
--
-- Ten overnight-eligible Love's Travel Stops, each in a different state and on
-- a different corridor, weighted to corridors the directory currently has zero
-- parking on. Every one must already have been inserted by INSERT-NET-NEW.sql
-- and therefore already carries an machine-checked coordinate.
--
${canary.map((r, i) => `--  ${String(i + 1).padStart(2)}. #${r.source_ref.padEnd(4)} ${r.city}, ${r.state}  ${String(r.interstate).padEnd(6)} ${r.parking_spaces} spaces`).join('\n')}

begin;

create temporary table _canary (source_ref text primary key, state char(2)) on commit drop;
insert into _canary values
${canary.map((r) => `  (${q(r.source_ref)}, ${q(r.state)})`).join(',\n')};

do $$
declare n integer;
begin
  -- 1. All ten resolve to exactly one unpublished Love's truck-stops row each.
  select count(*) into n
    from _canary c join public.locations l
      on l.state = c.state and substring(l.name from '#\\s*(\\d+)') = c.source_ref
   where l.deleted_at is null and l.category_slug = 'truck-stops'
     and l.source = 'loves-master-2026-07-27';
  if n <> 10 then raise exception 'Expected 10 canary rows, matched %.', n; end if;

  -- 2. COORDINATES REQUIRED.
  select count(*) into n
    from _canary c join public.locations l
      on l.state = c.state and substring(l.name from '#\\s*(\\d+)') = c.source_ref
   where l.lat is null or l.lng is null;
  if n <> 0 then raise exception '% canary row(s) have no coordinate.', n; end if;

  -- 3. OVERNIGHT REQUIRED. A non-overnight store may never enter a parking canary.
  select count(*) into n
    from _canary c join public.locations l
      on l.state = c.state and substring(l.name from '#\\s*(\\d+)') = c.source_ref
   where l.overnight_parking is not true or coalesce(l.parking_spaces, 0) < 1;
  if n <> 0 then raise exception '% canary row(s) are not overnight-eligible.', n; end if;

  -- 4. None already published (idempotent).
  select count(*) into n
    from _canary c join public.locations l
      on l.state = c.state and substring(l.name from '#\\s*(\\d+)') = c.source_ref
   where l.is_published;
  if n <> 0 then raise exception '% canary row(s) are already published.', n; end if;

  -- 5. Publish. is_featured and is_indexable untouched.
  update public.locations l
     set is_published = true, updated_at = now()
    from _canary c
   where l.state = c.state and substring(l.name from '#\\s*(\\d+)') = c.source_ref
     and l.category_slug = 'truck-stops' and l.source = 'loves-master-2026-07-27'
     and l.lat is not null and l.lng is not null;
  get diagnostics n = row_count;
  if n <> 10 then raise exception 'Expected to publish exactly 10 row(s), published %.', n; end if;
end $$;

commit;
`;
writeFileSync(`${OUT}/PUBLISH-CANARY.sql`, can);

/* ========================================================= 4. PER-STATE PUBLISH */
const overnightStates = [
  ...new Set(netNew.filter((r) => r.overnight_eligible === 'true').map((r) => r.state)),
].sort();
let pub = `-- Love's publication, ONE TRANSACTION PER STATE — GUARDED.
--
-- NOT EXECUTED. Run only after the canary has been verified, and only with a
-- separate publication authorization.
--
-- Publishes overnight-eligible Love's rows inserted by INSERT-NET-NEW.sql.
-- The 11 non-overnight Travel Stops are NEVER published by this file: the
-- overnight guard below excludes them, and they remain directory-only records.
--
-- ${overnightStates.length} states.

`;
for (const st of overnightStates) {
  const cnt = netNew.filter((r) => r.state === st && r.overnight_eligible === 'true').length;
  pub += `-- ---------------------------------------------------------------- ${st} (${cnt})
begin;
do $$
declare n integer;
begin
  select count(*) into n from public.locations
   where source = 'loves-master-2026-07-27' and state = ${q(st)}
     and category_slug = 'truck-stops' and not is_published
     and overnight_parking is true and coalesce(parking_spaces,0) > 0
     and lat is not null and lng is not null and deleted_at is null;
  if n <> ${cnt} then
    raise exception '${st}: expected ${cnt} publishable overnight row(s), found %.', n;
  end if;

  update public.locations
     set is_published = true, updated_at = now()
   where source = 'loves-master-2026-07-27' and state = ${q(st)}
     and category_slug = 'truck-stops' and not is_published
     and overnight_parking is true and coalesce(parking_spaces,0) > 0
     and lat is not null and lng is not null and deleted_at is null;
  get diagnostics n = row_count;
  if n <> ${cnt} then raise exception '${st}: expected to publish ${cnt}, published %.', n; end if;

  -- A non-overnight store must never have been published by this run.
  select count(*) into n from public.locations
   where source = 'loves-master-2026-07-27' and state = ${q(st)}
     and is_published and overnight_parking is not true;
  if n <> 0 then raise exception '${st}: % non-overnight row(s) were published.', n; end if;
end $$;
commit;

`;
}
writeFileSync(`${OUT}/PUBLISH-PER-STATE.sql`, pub);

writeFileSync(
  `${OUT}/canary.json`,
  JSON.stringify(
    canary.map((r) => ({
      source_ref: r.source_ref,
      name: r.name,
      city: r.city,
      state: r.state,
      interstate: r.interstate,
      exit_number: r.exit_number,
      lat: Number(r.lat),
      lng: Number(r.lng),
      parking_spaces: Number(r.parking_spaces),
      overnight_eligible: true,
      directory_url: `/directory/location/${detailSlug(r)}`,
      corridor_url: r.interstate
        ? `/directory/${r.interstate.toLowerCase().replace('-', '')}`
        : null,
    })),
    null,
    2,
  ) + '\n',
);

